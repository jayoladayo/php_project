# Writes an R script that reproduces the Results step with the user's names and labels.

rq <- function(x) paste0('"', gsub('"', '\\\\"', x), '"')
rvec <- function(x, numeric = FALSE) {
  if (numeric) paste0("c(", paste(ifelse(is.na(x), "NA", format(x, trim = TRUE, digits = 15)), collapse = ", "), ")")
  else paste0("c(", paste(ifelse(is.na(x), "NA", rq(x)), collapse = ", "), ")")
}
wrap_vec <- function(s, indent = "    ", width = 78) {
  parts <- strsplit(s, ", ", fixed = TRUE)[[1]]
  lines <- character(0); cur <- ""
  for (p in parts) {
    add <- if (nzchar(cur)) paste0(cur, ", ", p) else p
    if (nchar(add) > width && nzchar(cur)) { lines <- c(lines, paste0(cur, ",")); cur <- p } else cur <- add
  }
  paste(c(lines, cur), collapse = paste0("\n", indent))
}

make_r_code <- function(res, ds_name, file = NULL, sheet = NULL, df = NULL) {
  design <- res$design; map <- res$map; s <- res$settings; L <- s$labels
  terms <- doe_terms(design)
  col <- function(k) map[[k]]
  btc <- function(k) bt(map[[k]])
  resp <- bt(map$response)
  fk <- terms
  cols <- unique(c(map$response, vapply(fk, col, ""), if (nzchar(map$run %||% "")) map$run))
  out <- c(
    sprintf("# %s: %s", s$title %||% design$name, design$name),
    sprintf("# Generated by StatDesign Studio on %s. Reproduces every number on the Results tabs.", format(Sys.Date())),
    "",
    "library(car)       # Levene test, Type II/III sums of squares",
    "library(lmtest)    # Breusch-Pagan, Durbin-Watson, Breusch-Godfrey",
    "library(nortest)   # Anderson-Darling",
    "library(multcomp)  # Dunnett",
    if (design$key %in% c("LSD", "GLSD")) "library(coin)      # permutation test on ranks",
    "",
    "# ---- Data ----",
    if (!is.null(file)) sprintf("# Your file: data <- readxl::read_excel(%s%s)", rq(file), if (!is.null(sheet)) sprintf(", sheet = %s", rq(sheet)) else ""),
    sprintf("# The data used in the app (dataset “%s”):", ds_name),
    "data <- data.frame(")
  dcols <- vapply(cols, function(cn) {
    v <- df[[cn]]
    num <- cn == map$response || (nzchar(map$run %||% "") && cn == map$run && all(!is.na(suppressWarnings(as.numeric(v[!is.na(v)])))))
    vals <- if (num) rvec(suppressWarnings(as.numeric(v)), TRUE) else rvec(as.character(v))
    sprintf("  %s = %s", bt(cn), wrap_vec(vals))
  }, "")
  out <- c(out, paste(dcols, collapse = ",\n"), "  , check.names = FALSE)", "")
  out <- c(out, "# Factors, with the labels and order chosen in the app")
  for (k in fk) {
    Lk <- L[[k]]
    out <- c(out, sprintf("data$%s <- factor(data$%s,\n  levels = %s,\n  labels = %s)", btc(k), btc(k),
                          rvec(Lk$code), rvec(make.unique(Lk$label))))
  }
  out <- c(out, sprintf("data <- data[!is.na(data$%s), ]", resp))
  if (nzchar(map$run %||% "")) out <- c(out, sprintf("data <- data[order(data$%s), ]  # run order, for the independence checks", bt(map$run)))
  form <- paste(resp, "~", paste(vapply(fk, btc, ""), collapse = " + "))
  trt <- btc("treatment")
  out <- c(out, "",
    sprintf("alpha <- %s", format(res$alpha)), sprintf("conf  <- %s", format(res$conf)), "",
    sprintf("# ---- 1. ANOVA (%s) ----", design$short),
    sprintf("model <- aov(%s, data = data)", form),
    if ((s$sstype %||% "I") == "I") "summary(model)            # Type I (sequential) sums of squares, as in class"
    else c("options(contrasts = c(\"contr.sum\", \"contr.poly\"))",
           sprintf("car::Anova(lm(%s, data = data), type = %s)", form, if (s$sstype == "II") 2 else 3)),
    "df_error <- df.residual(model)",
    sprintf("qf(1 - alpha, %d, df_error)   # F critical for %s", nlevels(res$data$treatment) - 1, map$treatment),
    "",
    "# ---- 2. Assumptions ----",
    "shapiro.test(rstandard(model))              # normality",
    "ad.test(rstandard(model))                   # normality",
    "bptest(model)                               # equal variance",
    sprintf("leveneTest(%s ~ %s, data = data)   # equal variance across treatments", resp, trt),
    "dwtest(model, alternative = \"two.sided\")    # independence",
    "bgtest(model, order = 1)                    # independence",
    "plot(model, 2)                              # QQ plot",
    "plot(model, 1)                              # residuals vs fitted",
    "plot(residuals(model), type = \"o\", xlab = \"Run order\", ylab = \"Residuals\")",
    "",
    "# ---- 3. Post-hoc ----",
    "# Fisher LSD, Bonferroni and Scheffé use the model's error mean square",
    "# (the same results as agricolae::LSD.test and agricolae::scheffe.test).",
    "pairwise_mse <- function(model, factor, data, conf = 0.95) {",
    "  y <- model.response(model.frame(model)); g <- data[[factor]]",
    "  mse <- deviance(model) / df.residual(model); dfe <- df.residual(model)",
    "  m <- tapply(y, g, mean); n <- tapply(y, g, length); k <- length(m)",
    "  ij <- combn(k, 2); i <- ij[1, ]; j <- ij[2, ]; np <- length(i)",
    "  diff <- m[j] - m[i]; se <- sqrt(mse * (1 / n[i] + 1 / n[j])); t <- diff / se",
    "  data.frame(pair = paste(names(m)[j], \"-\", names(m)[i]), diff = round(diff, 4),",
    "             p_LSD = 2 * pt(-abs(t), dfe),",
    "             p_Bonferroni = pmin(1, np * 2 * pt(-abs(t), dfe)),",
    "             p_Scheffe = pf(t^2 / (k - 1), k - 1, dfe, lower.tail = FALSE),",
    "             LSD_lwr = diff - qt(1 - (1 - conf) / 2, dfe) * se, LSD_upr = diff + qt(1 - (1 - conf) / 2, dfe) * se,",
    "             row.names = NULL)",
    "}")
  for (t in compared_terms(design)) {
    tv <- btc(t); tq <- rq(map[[t]])
    ctrl <- if (t == "treatment") label_of(L$treatment, s$control) else NULL
    out <- c(out,
      sprintf("TukeyHSD(model, %s, conf.level = conf)", tq),
      sprintf("pairwise_mse(model, %s, data, conf)", tq),
      sprintf("set.seed(%s)", format(s$seed %||% 1)),
      sprintf("data_d <- data; data_d$%s <- relevel(data_d$%s, ref = %s)", tv, tv, rq(ctrl %||% levels(res$data[[t]])[1])),
      sprintf("dunnett <- glht(aov(%s, data = data_d), linfct = mcp(%s = \"Dunnett\"))", form, tv),
      "summary(dunnett); confint(dunnett, level = conf)")
  }
  out <- c(out, "", "# ---- 4. Non-parametric alternative ----")
  if (design$key == "CRD") {
    out <- c(out,
      sprintf("kruskal.test(%s ~ %s, data = data)", resp, trt),
      "# Dunn test with Holm adjustment (same as FSA::dunnTest)",
      "dunn <- function(y, g) {",
      "  g <- droplevels(factor(g)); N <- length(y); r <- rank(y)",
      "  R <- tapply(r, g, mean); n <- tapply(r, g, length); ties <- table(y)",
      "  v <- N * (N + 1) / 12 - sum(ties^3 - ties) / (12 * (N - 1))",
      "  ij <- combn(nlevels(g), 2); i <- ij[1, ]; j <- ij[2, ]",
      "  z <- (R[j] - R[i]) / sqrt(v * (1 / n[i] + 1 / n[j])); p <- 2 * pnorm(-abs(z))",
      "  data.frame(pair = paste(levels(g)[j], \"-\", levels(g)[i]), Z = z, p_unadj = p, p_holm = p.adjust(p, \"holm\"), row.names = NULL)",
      "}",
      sprintf("dunn(data$%s, data$%s)", resp, trt),
      sprintf("pairwise.wilcox.test(data$%s, data$%s, p.adjust.method = \"bonferroni\")", resp, trt))
  } else if (design$key == "RCBD") {
    blk <- btc("block")
    out <- c(out,
      sprintf("cell <- aggregate(%s ~ %s + %s, data = data, FUN = mean)  # one value per block and treatment", resp, trt, blk),
      sprintf("friedman.test(%s ~ %s | %s, data = cell)", resp, trt, blk),
      sprintf("quade.test(%s ~ %s | %s, data = cell)", resp, trt, blk),
      "# Nemenyi test (same as PMCMRplus::frdAllPairsNemenyiTest)",
      sprintf("ranks <- t(apply(xtabs(%s ~ %s + %s, data = cell), 1, rank))", resp, blk, trt),
      "k <- ncol(ranks); b <- nrow(ranks); R <- colMeans(ranks); ij <- combn(k, 2)",
      "q <- abs(R[ij[2, ]] - R[ij[1, ]]) / sqrt(k * (k + 1) / (6 * b))",
      "data.frame(pair = paste(names(R)[ij[2, ]], \"-\", names(R)[ij[1, ]]), diff = R[ij[2, ]] - R[ij[1, ]],",
      "           p = ptukey(q * sqrt(2), k, Inf, lower.tail = FALSE), row.names = NULL)",
      sprintf("cell <- cell[order(cell$%s, cell$%s), ]", blk, trt),
      sprintf("pairwise.wilcox.test(cell$%s, cell$%s, paired = TRUE, p.adjust.method = \"bonferroni\")", resp, trt))
  } else {
    for (t in compared_terms(design)) {
      blocks <- setdiff(terms, t)
      out <- c(out,
        sprintf("# %s: remove %s, rank the residuals, permutation test (class approach)", map[[t]], paste(vapply(blocks, col, ""), collapse = ", ")),
        sprintf("data$rank_resid <- rank(residuals(lm(%s ~ %s, data = data)))", resp, paste(vapply(blocks, btc, ""), collapse = " + ")),
        sprintf("set.seed(%s)", format(s$seed %||% 1)),
        sprintf("oneway_test(rank_resid ~ %s, data = data, distribution = approximate(nresample = 10000))", btc(t)),
        sprintf("pairwise.wilcox.test(data$rank_resid, data$%s, p.adjust.method = \"bonferroni\")", btc(t)))
    }
  }
  paste(Filter(Negate(is.null), out), collapse = "\n")
}
