# R script for one, two and k sample results, written in the style of the class script.

make_samples_code <- function(res, ds_name) {
  s <- res$settings; alt <- s$alt %||% "two.sided"; conf <- s$conf %||% 0.95; mu <- s$mu %||% 0
  num <- function(x) wrap_vec(rvec(x, TRUE))
  sig <- s$sigma; sig2 <- s$sigma2 %||% s$sigma
  has_z <- !is.null(res$tests$z)
  head <- c(sprintf("# %s", s$title %||% "Sample comparison"),
            sprintf("# Generated by StatDesign Studio on %s from dataset “%s”.", format(Sys.Date()), ds_name),
            "# Follows the class script: One, Two & K Samples Analysis.", "")
  args <- sprintf('alternative = "%s", conf.level = %s', alt, format(conf))
  out <- switch(res$kind,
    one = c(head,
      if (has_z) "library(BSDA)   # z.test", "",
      sprintf("x1 <- %s", num(res$data[[1]])), "",
      "# Descriptive", "mean(x1); median(x1); sd(x1); summary(x1)", "",
      "# Normality", "shapiro.test(x1)", "",
      "# One sample testing for location",
      if (has_z) sprintf("z.test(x = x1, sigma.x = %s, mu = %s, %s)", format(sig), format(mu), args),
      sprintf("t.test(x = x1, mu = %s, %s)", format(mu), args),
      sprintf("wilcox.test(x = x1, mu = %s, %s, conf.int = TRUE, exact = FALSE)", format(mu), args),
      sprintf("binom.test(sum(x1 > %s), sum(x1 != %s), 0.5, alternative = \"%s\")   # sign test", format(mu), format(mu), alt)),
    two = c(head,
      "library(car)    # leveneTest", if (has_z) "library(BSDA)   # z.test", "",
      sprintf("x1 <- %s   # %s", num(res$data[[1]]), s$names[1]),
      sprintf("x2 <- %s   # %s", num(res$data[[2]]), s$names[2]), "",
      "# Normality of each sample", "shapiro.test(x1); shapiro.test(x2)", "",
      "# Are the variances equal?", "var.test(x1, x2)",
      "y <- c(x1, x2); g <- factor(rep(c(\"x1\", \"x2\"), c(length(x1), length(x2))))",
      "leveneTest(y ~ g)", "",
      "# Two samples testing for location, independent samples",
      if (has_z) sprintf("z.test(x = x1, y = x2, sigma.x = %s, sigma.y = %s, mu = %s, %s)", format(sig), format(sig2), format(mu), args),
      sprintf("t.test(x = x1, y = x2, var.equal = TRUE, mu = %s, %s)", format(mu), args),
      sprintf("t.test(x = x1, y = x2, var.equal = FALSE, mu = %s, %s)", format(mu), args),
      sprintf("wilcox.test(x = x1, y = x2, mu = %s, %s, conf.int = TRUE, exact = FALSE)", format(mu), args)),
    paired = c(head,
      sprintf("x1 <- %s   # %s", num(res$data[[1]]), s$names[1]),
      sprintf("x2 <- %s   # %s", num(res$data[[2]]), s$names[2]),
      "ok <- complete.cases(x1, x2); x1 <- x1[ok]; x2 <- x2[ok]", "",
      "# Normality of the differences", "shapiro.test(x1 - x2)", "",
      "# Two samples testing for location, dependent (paired) samples",
      sprintf("t.test(x = x1, y = x2, mu = %s, %s, paired = TRUE)", format(mu), args),
      sprintf("wilcox.test(x = x1, y = x2, mu = %s, %s, conf.int = TRUE, exact = FALSE, paired = TRUE)", format(mu), args),
      sprintf("d <- x1 - x2; binom.test(sum(d > %s), sum(d != %s), 0.5, alternative = \"%s\")   # sign test", format(mu), format(mu), alt)),
    k = {
      lv <- levels(res$data$g)
      c(head, "library(car)    # leveneTest", "",
        sprintf("response <- %s", num(res$data$y)),
        sprintf("treatments <- factor(%s,\n  levels = %s)", wrap_vec(rvec(as.character(res$data$g))), rvec(lv)), "",
        "# One Way ANOVA - F test, parametric approach",
        "one.aov <- aov(response ~ treatments)   # assuming equal variances",
        "summary(one.aov)", "",
        "# Assumptions", "shapiro.test(residuals(one.aov))", "leveneTest(response ~ treatments)", "bartlett.test(response ~ treatments)", "",
        "# Alternative: Welch test",
        "oneway.test(response ~ treatments, var.equal = TRUE)    # when variances are equal",
        "oneway.test(response ~ treatments, var.equal = FALSE)   # when variances are not equal", "",
        "# One Way ANOVA - Kruskal-Wallis test, non-parametric approach",
        "kruskal.test(response ~ treatments)", "",
        "# Post-hoc",
        sprintf("TukeyHSD(one.aov, conf.level = %s)", format(conf)),
        "# Games-Howell (unequal variances)",
        "games_howell <- function(y, g, conf = 0.95) {",
        "  m <- tapply(y, g, mean); v <- tapply(y, g, var); n <- tapply(y, g, length); k <- length(m)",
        "  ij <- combn(k, 2); i <- ij[1, ]; j <- ij[2, ]",
        "  a <- v[i] / n[i]; b <- v[j] / n[j]; se <- sqrt(a + b)",
        "  df <- (a + b)^2 / (a^2 / (n[i] - 1) + b^2 / (n[j] - 1)); q <- abs(m[j] - m[i]) / se * sqrt(2)",
        "  data.frame(pair = paste(names(m)[j], \"-\", names(m)[i]), diff = m[j] - m[i],",
        "             p = ptukey(q, k, df, lower.tail = FALSE), row.names = NULL)",
        "}",
        sprintf("games_howell(response, treatments, %s)", format(conf)),
        "# Dunn test with Holm adjustment (same as FSA::dunnTest)",
        "dunn <- function(y, g) {",
        "  N <- length(y); r <- rank(y); R <- tapply(r, g, mean); n <- tapply(r, g, length); ties <- table(y)",
        "  v <- N * (N + 1) / 12 - sum(ties^3 - ties) / (12 * (N - 1))",
        "  ij <- combn(nlevels(g), 2); i <- ij[1, ]; j <- ij[2, ]",
        "  z <- (R[j] - R[i]) / sqrt(v * (1 / n[i] + 1 / n[j])); p <- 2 * pnorm(-abs(z))",
        "  data.frame(pair = paste(levels(g)[j], \"-\", levels(g)[i]), Z = z, p_holm = p.adjust(p, \"holm\"), row.names = NULL)",
        "}",
        "dunn(response, treatments)")
    })
  paste(Filter(Negate(is.null), out), collapse = "\n")
}
